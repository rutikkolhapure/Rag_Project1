"""Central settings. Everything you may want to tweak lives here."""
from __future__ import annotations

import os
from pathlib import Path
from urllib.parse import urlparse

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent

# Loads ROOT/.env into environment variables (silently does nothing if the file is missing).
#
# >>> LLM KEY (1 of 2 places in code that touch it): the key is LOADED here <<<
# You enter the LLM settings and key in the file  .env  (next to build_index.py), not in this file:
#       LLM_PROVIDER=openai
#       LLM_BASE_URL=...   LLM_MODEL=...   LLM_API_KEY=...
# Do NOT paste the key into any .py file.
load_dotenv(ROOT / ".env")

# ---- folders -------------------------------------------------------------
DATA_DIR = ROOT / "data"    # drop your HR policy PDFs here
INDEX_DIR = ROOT / "index"  # generated by build_index.py, safe to delete

# ---- chunking (measured in words) ------------------------------------------
CHUNK_WORDS = 250           # target size of one chunk
CHUNK_OVERLAP_WORDS = 50    # words repeated between neighbouring chunks
MIN_CHUNK_WORDS = 40        # smaller leftovers are merged into a neighbour

# ---- retrieval -------------------------------------------------------------
TOP_K = 6                   # passages handed to the LLM per question

# ---- generation (the LLM that writes the answer) -----------------------------
# All of these are set in .env, not here.
#   LLM_PROVIDER  "openai"    any service that speaks the OpenAI "chat completions" API: OpenAI,
#                             Google Gemini, Mistral, Groq, DeepSeek, Together, OpenRouter, Azure
#                             AI Foundry, and local servers such as Ollama, LM Studio or vLLM
#                 "anthropic" Claude (needs:  pip install anthropic)
#   LLM_BASE_URL  the service's API address (openai provider only; deliberately has no default,
#                 so your key can never be sent to a service you did not choose)
#   LLM_MODEL     the model name your service expects
#   LLM_API_KEY   your key (for the anthropic provider: ANTHROPIC_API_KEY)
LLM_PROVIDER = (os.getenv("LLM_PROVIDER") or "openai").strip().lower()
LLM_BASE_URL = (os.getenv("LLM_BASE_URL") or "").strip()
LLM_MODEL = (os.getenv("LLM_MODEL") or ("claude-opus-5-5" if LLM_PROVIDER == "anthropic" else "")).strip()

MAX_ANSWER_TOKENS = 16000   # anthropic provider only: headroom for Claude's reasoning plus the answer
LLM_TIMEOUT_SECONDS = 120   # openai provider: give up on a request after this long
HISTORY_TURNS = 3           # previous Q&A pairs remembered in chat mode

# ---- vector database + embeddings (optional; all set in .env) ----------------------
# With VECTOR_STORE=chroma, every passage is turned into an embedding (a list of numbers that captures
# its meaning) and stored in a Chroma database, so questions also find passages that use different
# words. The existing keyword search keeps running next to it and the two rankings are merged.
#   VECTOR_STORE          "chroma", or empty for keyword search only
#   CHROMA_HOST/PORT/SSL  your Chroma server (self-hosted). For Chroma Cloud leave CHROMA_HOST empty
#                         and fill CHROMA_API_KEY, CHROMA_TENANT and CHROMA_DATABASE instead.
#   CHROMA_COLLECTION     name of the collection this project owns (it is deleted and rebuilt on re-index!)
#   CHROMA_MAX_DISTANCE   vector matches farther than this (cosine distance, 0 = identical) are ignored
#   EMBED_BASE_URL/MODEL/API_KEY   an OpenAI-compatible /embeddings service (same idea as the LLM_ ones)
VECTOR_STORE = (os.getenv("VECTOR_STORE") or "").strip().lower()
CHROMA_HOST = (os.getenv("CHROMA_HOST") or "").strip()
CHROMA_PORT = (os.getenv("CHROMA_PORT") or "8000").strip()
CHROMA_SSL = (os.getenv("CHROMA_SSL") or "").strip().lower() in {"1", "true", "yes", "on"}
CHROMA_TENANT = (os.getenv("CHROMA_TENANT") or "").strip()
CHROMA_DATABASE = (os.getenv("CHROMA_DATABASE") or "").strip()
CHROMA_COLLECTION = (os.getenv("CHROMA_COLLECTION") or "hr_policies").strip()
CHROMA_MAX_DISTANCE = (os.getenv("CHROMA_MAX_DISTANCE") or "0.8").strip()
EMBED_BASE_URL = (os.getenv("EMBED_BASE_URL") or "").strip()
EMBED_MODEL = (os.getenv("EMBED_MODEL") or "").strip()
EMBED_BATCH_SIZE = 32       # passages sent per embeddings request
EMBED_TIMEOUT_SECONDS = 120

PROVIDERS = ("openai", "anthropic")


def llm_api_key() -> str:
    """The key for the selected provider, read from the environment each time it is needed."""
    if LLM_PROVIDER == "anthropic":
        return (os.getenv("ANTHROPIC_API_KEY") or os.getenv("ANTHROPIC_AUTH_TOKEN") or "").strip()
    return (os.getenv("LLM_API_KEY") or "").strip()


def is_local_url(url: str) -> bool:
    """True for a server on this machine (Ollama, LM Studio ...), which normally needs no key."""
    return (urlparse(url).hostname or "").lower() in {"localhost", "127.0.0.1", "::1"}


def llm_setup_problem() -> str | None:
    """What is still missing from .env before answers can be written, or None when it is ready."""
    if LLM_PROVIDER not in PROVIDERS:
        return f"LLM_PROVIDER='{LLM_PROVIDER}' is not supported. Use one of: {', '.join(PROVIDERS)}."
    if LLM_PROVIDER == "anthropic":
        return None if llm_api_key() else "ANTHROPIC_API_KEY is empty in the .env file."
    missing = [name for name, value in (("LLM_BASE_URL", LLM_BASE_URL), ("LLM_MODEL", LLM_MODEL)) if not value]
    if not missing and not llm_api_key() and not is_local_url(LLM_BASE_URL):
        missing.append("LLM_API_KEY")
    return f"{', '.join(missing)} not set in the .env file." if missing else None


# ---- vector database + embeddings helpers -------------------------------------------

def embed_api_key() -> str:
    """The key for the embeddings service, read from the environment each time it is needed."""
    return (os.getenv("EMBED_API_KEY") or "").strip()


def chroma_api_key() -> str:
    """The key for Chroma (Chroma Cloud, or a gateway in front of your own server)."""
    return (os.getenv("CHROMA_API_KEY") or "").strip()


def chroma_is_cloud() -> bool:
    """Chroma Cloud is used when no CHROMA_HOST is given but a tenant and database are."""
    return not CHROMA_HOST and bool(CHROMA_TENANT and CHROMA_DATABASE)


def chroma_max_distance() -> float | None:
    """The distance cut-off as a number, or None for 'no cut-off' (CHROMA_MAX_DISTANCE=0)."""
    value = float(CHROMA_MAX_DISTANCE)
    return value if value > 0 else None


def vector_store_problem() -> str | None:
    """What is missing or wrong in .env before Chroma can be used, or None when it is ready."""
    if VECTOR_STORE != "chroma":
        return f"VECTOR_STORE='{VECTOR_STORE}' is not supported. Use 'chroma' (or leave it empty)."
    problems: list[str] = []
    if not CHROMA_HOST and not chroma_is_cloud():
        problems.append("CHROMA_HOST is not set (for Chroma Cloud, set CHROMA_API_KEY, CHROMA_TENANT and "
                        "CHROMA_DATABASE instead)")
    elif chroma_is_cloud() and not chroma_api_key():
        problems.append("CHROMA_API_KEY is not set")
    if CHROMA_HOST and not CHROMA_PORT.isdigit():
        problems.append(f"CHROMA_PORT='{CHROMA_PORT}' is not a number")
    if CHROMA_HOST and chroma_api_key() and not CHROMA_SSL and not is_local_url(f"http://{CHROMA_HOST}"):
        problems.append("CHROMA_API_KEY would be sent unencrypted to a remote server; set CHROMA_SSL=true")
    try:
        float(CHROMA_MAX_DISTANCE)
    except ValueError:
        problems.append(f"CHROMA_MAX_DISTANCE='{CHROMA_MAX_DISTANCE}' is not a number")
    if not CHROMA_COLLECTION:
        problems.append("CHROMA_COLLECTION is empty")
    missing = [name for name, value in (("EMBED_BASE_URL", EMBED_BASE_URL), ("EMBED_MODEL", EMBED_MODEL)) if not value]
    if missing:
        problems.append(f"{', '.join(missing)} not set")
    elif not embed_api_key() and not is_local_url(EMBED_BASE_URL):
        problems.append("EMBED_API_KEY is not set")
    return "; ".join(problems) + " (in the .env file)" if problems else None
